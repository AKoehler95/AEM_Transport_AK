"""
AEM Composite Source Config Generator

User-defined Parameters
--------------------------------------------------------------------------------
  N_CONFIGS   : total number of configs to generate
  WS          : source zone width [m] — all circle centres must lie in [0, WS]
  Y_SPAN_MIN  : minimum total vertical extent of source clusters [m]
  Y_SPAN_MAX  : maximum total vertical extent of source clusters [m]
  ORIENTATION : "horizontal" or "vertical", applied to every config in the batch
  OUTPUT_DIR  : folder where JSON configs are written
  RANDOM_SEED : set to an integer for reproducibility, or None for a fresh run

Random Distrubution Setup for each config
--------------------------------------------------------------------------------
Each config is built in three stages:

  1. ARCHETYPE  (discrete uniform over 10 archetypes)
     One of ten spatial placement patterns is drawn with equal probability:
       A  Vertical stack   — single x column, exponentially distributed gaps
       B  Horizontal spread — each cluster confined to its own x sub-band
       C  Top heavy        — all clusters in the upper half (y > 0)
       D  Bottom heavy     — all clusters in the lower half (y < 0)
       E  Tight pack       — clusters very close together (tiny gaps)
       F  Scattered        — fully random (x, y) positions across the domain
       G  Diagonal         — x drifts linearly from one side to the other as y changes
       H  Two groups       — two tight sub-groups with a large void between them
       I  Outlier          — one cluster isolated far from the main group
       J  Dense centre     — clusters bunched near y=0, spacing grows outward

  2. CONFIG-LEVEL PARAMETERS
     Total vertical span  ~ Uniform(Y_SPAN_MIN, Y_SPAN_MAX)   [m]
     Number of clusters   ~ DiscreteUniform({2, 3, 4, 5}),
                            weighted [1, 2, 3, 2] so 3-4 clusters are most common

  3. PER-CLUSTER PARAMETERS  (drawn independently for every cluster)
     Cluster height (ls)  ~ Uniform(0.3*WS, 0.5*Y_SPAN_MAX / n_clusters)
                            capped so total heights don't consume the full span
     Cluster x-centre     ~ Uniform(r_max, WS - r_max)
                            hard-clamped so circles never exceed [0, WS]
     Radius pool          ~ DiscreteUniform({TINY, SMALL, MED, LARGE, MIXED})
                            — determines the characteristic circle size for
                              this cluster; radii are scaled to WS so the
                              relative packing density is preserved regardless
                              of WS
     Concentration pool   ~ DiscreteUniform({LOW, MID, HIGH, FULL})
     Number of circles    ~ DiscreteUniform(5, 20)
     Individual radius r  ~ DiscreteUniform over chosen radius pool
     Individual conc   c  ~ DiscreteUniform over chosen concentration pool

     Inter-cluster gaps depend on archetype:
       Most archetypes  : gaps ~ Exponential(1.0) then rescaled to fill
                          the remaining span after subtracting cluster heights.
                          Exponential produces high variance — most gaps small,
                          occasionally one large gap.
       Tight-pack (E)   : gaps ~ Uniform(0.02*WS, 0.1*Y_SPAN_MAX)  (small)
       Two-groups (H)   : void gap ~ Uniform(0.3*Y_SPAN_MAX, 0.7*Y_SPAN_MAX),
                          intra-group gaps ~ Uniform(0.01, 0.1) * WS  (tiny)
       Outlier (I)      : outlier gap ~ Uniform(0.4*Y_SPAN_MAX, 0.9*Y_SPAN_MAX)

Boundary condition check with Ws
--------------------------------------------------------------------------------
  make_cluster()       : builds a hexagonal grid of candidate positions.
                         Column x-coordinates are generated by centering on cx
                         then clamping every column to [r_max, WS - r_max].
                         No candidate outside this range is ever placed.
  make_cluster_narrow(): same, but additionally restricts columns to the band
                         [cx - half_width, cx + half_width], used for archetypes
                         that need distinct x sub-bands (B, G).
  Post-generation check: after building each config, every element x is checked
                         against [0, WS]. Configs with violations are discarded.

Orientation Note
--------------------------------------------------------------------------------
  "horizontal" : elements placed at any y; dom_ymax set above clusters.
  "vertical"   : the simulation mirrors each element across y=0, so all
                 element centres must be at y < 0. The generator shifts the
                 entire cluster stack downward so that the topmost element edge
                 sits at y = -(r_max + 0.15) m, safely below the boundary.
                 dom_ymax is forced to 0.

FIXED SIMULATION PARAMETERS  (same for all configs)
--------------------------------------------------------------------------------
  alpha_l = 2.0,  alpha_t = 0.2,  ca = 8.0,  gamma = 3.5
  dom_inc = 1.0,  num_cp = 40,    num_terms = 5
================================================================================
"""

import json, os, math, random

#  USER-DEFINED PARAMETERS
N_CONFIGS   = 10         # total configs to generate
WS          = 0.5        # source zone width [m]
Y_SPAN_MIN  = 5.0        # minimum total vertical source span [m]
Y_SPAN_MAX  = 25.0       # maximum total vertical source span [m]
ORIENTATION = "vertical"  # "horizontal" or "vertical"
OUTPUT_DIR  = "configs_test_batch"
RANDOM_SEED = 2027       # integer for reproducibility, or None


random.seed(RANDOM_SEED)
os.makedirs(OUTPUT_DIR, exist_ok=True)

# Radius pools — defined relative to WS so packing scales with source width
_r = WS
TINY  = [round(_r * f, 6) for f in [0.016, 0.020, 0.024]]
SMALL = [round(_r * f, 6) for f in [0.024, 0.030, 0.036]]
MED   = [round(_r * f, 6) for f in [0.036, 0.044, 0.050]]
LARGE = [round(_r * f, 6) for f in [0.056, 0.064, 0.076, 0.080]]
MIXED = [round(_r * f, 6) for f in [0.016, 0.024, 0.036, 0.050, 0.064, 0.080]]

ALL_RPOOLS = [TINY, SMALL, MED, LARGE, MIXED]

# Concentration pools [mg/L]
LOW_C  = [3.0, 5.0, 8.0]
MID_C  = [10.0, 15.0, 20.0]
HIGH_C = [25.0, 35.0, 50.0]
FULL_C = [3.0, 5.0, 8.0, 10.0, 15.0, 20.0, 25.0, 35.0, 50.0]
ALL_CPOOLS = [LOW_C, MID_C, HIGH_C, FULL_C]

# Number-of-clusters weights: index = n_clusters - 2  =>  [2, 3, 4, 5]
N_CLUSTER_WEIGHTS = [1, 2, 3, 2]


# Core packing functions, WS constraint enforced here
def make_cluster(cx, cy, n_target, rpool, cpool, tag, start_idx=0, ls=None):
    """
    Hex-pack up to n_target circles into a cluster centred at (cx, cy).
    All columns are clamped to [r_max, WS - r_max] — the Ws constraint.
    ls: optional hard vertical cap (half-height either side of cy).
    """
    r_max = max(rpool)
    col_sp = 2.0 * r_max * 1.03               # column pitch (2r + 3% clearance)
    row_sp = col_sp * math.sqrt(3) / 2        # row pitch for hex packing

    # Build column x-positions centred on cx, clamp strictly inside WS
    n_cols = max(1, int(WS / col_sp))
    col_xs = []
    for ci in range(n_cols):
        x = cx - (n_cols - 1) * col_sp / 2 + ci * col_sp
        x = max(r_max, min(WS - r_max, x))    # ← WS enforced here
        col_xs.append(x)

    # Keep only columns within ~6 radii of cx (avoids wasted candidates)
    half_w = r_max * 6
    col_xs = [x for x in col_xs if abs(x - cx) <= half_w + col_sp]
    if not col_xs:
        col_xs = [max(r_max, min(WS - r_max, cx))]

    n_rows = max(n_target * 5, 100)
    candidates = []
    for ci, x in enumerate(col_xs):
        for ri in range(-n_rows // 2, n_rows // 2 + 1):
            y = cy + ri * row_sp + (ci % 2) * row_sp * 0.5
            if ls is not None and abs(y - cy) > ls / 2:
                continue
            candidates.append((math.hypot(x - cx, y - cy), x, y))

    candidates.sort()
    placed, elements = [], []
    for _, x, y in candidates:
        if len(elements) >= n_target:
            break
        r = random.choice(rpool)
        c = random.choice(cpool)
        if not any(math.hypot(x - px, y - py) < r + pr - 1e-9
                   for px, py, pr in placed):
            placed.append((x, y, r))
            elements.append({
                "kind": "circle",
                "x": round(x, 5),
                "y": round(y, 5),
                "r": round(r, 5),
                "c": round(c, 2),
                "id": f"{tag}_{start_idx + len(elements)}"
            })
    return elements


def make_cluster_narrow(cx, cy, half_width, n_target, rpool, cpool,
                        tag, start_idx=0, ls=None):
    """
    Like make_cluster but columns are further restricted to
    [cx - half_width, cx + half_width].  Used for archetypes that
    need distinct horizontal sub-bands within WS.
    The outer [r_max, WS - r_max] clamp still applies.
    """
    r_max = max(rpool)
    col_sp = 2.0 * r_max * 1.03
    row_sp = col_sp * math.sqrt(3) / 2

    x_lo = max(r_max, cx - half_width)
    x_hi = min(WS - r_max, cx + half_width)
    if x_lo > x_hi:
        x_lo = max(r_max, 0.0)
        x_hi = min(WS - r_max, WS)

    col_xs, x = [], x_lo
    while x <= x_hi + 1e-9:
        col_xs.append(x)
        x += col_sp
    if not col_xs:
        col_xs = [max(r_max, min(WS - r_max, cx))]

    n_rows = max(n_target * 5, 100)
    candidates = []
    for ci, x in enumerate(col_xs):
        for ri in range(-n_rows // 2, n_rows // 2 + 1):
            y = cy + ri * row_sp + (ci % 2) * row_sp * 0.5
            if ls is not None and abs(y - cy) > ls / 2:
                continue
            candidates.append((math.hypot(x - cx, y - cy), x, y))

    candidates.sort()
    placed, elements = [], []
    for _, x, y in candidates:
        if len(elements) >= n_target:
            break
        r = random.choice(rpool)
        c = random.choice(cpool)
        if not any(math.hypot(x - px, y - py) < r + pr - 1e-9
                   for px, py, pr in placed):
            placed.append((x, y, r))
            elements.append({
                "kind": "circle",
                "x": round(x, 5),
                "y": round(y, 5),
                "r": round(r, 5),
                "c": round(c, 2),
                "id": f"{tag}_{start_idx + len(elements)}"
            })
    return elements


# Shared helpers
def sample_n_clusters():
    """DiscreteUniform weighted toward 3-4 clusters."""
    return random.choices([2, 3, 4, 5], weights=N_CLUSTER_WEIGHTS, k=1)[0]


def sample_total_span():
    """Uniform(Y_SPAN_MIN, Y_SPAN_MAX)."""
    return random.uniform(Y_SPAN_MIN, Y_SPAN_MAX)


def sample_cluster_ls(n_clusters, total_span):
    """Uniform(0.3*WS, cap) where cap keeps total heights < total_span."""
    cap = min(0.5 * total_span / n_clusters, 0.4 * Y_SPAN_MAX)
    lo  = 0.3 * WS
    return random.uniform(lo, max(lo * 1.1, cap))


def sample_cx():
    """Uniform(0.05*WS, 0.95*WS)."""
    return random.uniform(0.05 * WS, 0.95 * WS)


def expo_gaps(n, budget):
    """
    n gap values drawn from Exponential(1.0), then rescaled to sum to budget.
    High variance: usually a mix of small and large gaps.
    """
    raw = [random.expovariate(1.0) + 0.05 for _ in range(n)]
    s = sum(raw)
    return [max(0.02, g / s * budget) for g in raw]


def build_stack(n_clusters, total_span, cx_fn, ls_fn, gap_fn, tag_prefix, cfg_id,
                narrow_hw=None):
    """
    Generic vertical stacker used by most archetypes.
    cx_fn(k)  : returns x-centre for cluster k
    ls_fn(k)  : returns vertical span for cluster k
    gap_fn(k) : returns gap below cluster k  (k in 0..n-2)
    narrow_hw : if not None, use make_cluster_narrow with this half-width
    """
    ls_list = [ls_fn(k) for k in range(n_clusters)]
    gaps    = [gap_fn(k) for k in range(n_clusters - 1)]
    y = (sum(ls_list) + sum(gaps)) / 2

    elems, start = [], 0
    for k in range(n_clusters):
        cx  = cx_fn(k)
        cy  = y - ls_list[k] / 2
        rp  = random.choice(ALL_RPOOLS)
        cp  = random.choice(ALL_CPOOLS)
        n   = random.randint(5, 20)
        tag = f"{tag_prefix}{k}_{cfg_id}"
        if narrow_hw is not None:
            c = make_cluster_narrow(cx, cy, narrow_hw, n, rp, cp,
                                    tag, start_idx=start, ls=ls_list[k])
        else:
            c = make_cluster(cx, cy, n, rp, cp,
                             tag, start_idx=start, ls=ls_list[k])
        elems.extend(c)
        start += len(c)
        y -= ls_list[k] + (gaps[k] if k < n_clusters - 1 else 0)
    return elems


# Archetype builders
def archetype_vertical_stack(cfg_id, n_clusters):
    """A: Single x column, exponentially distributed gaps."""
    total = sample_total_span()
    ls_list = [sample_cluster_ls(n_clusters, total) for _ in range(n_clusters)]
    budget  = max(total - sum(ls_list), 0.3 * (n_clusters - 1))
    gaps    = expo_gaps(n_clusters - 1, budget)
    cx      = sample_cx()
    return build_stack(n_clusters, total,
                       cx_fn=lambda k: cx,
                       ls_fn=lambda k: ls_list[k],
                       gap_fn=lambda k: gaps[k],
                       tag_prefix="vs", cfg_id=cfg_id)


def archetype_horizontal_spread(cfg_id, n_clusters):
    """B: Each cluster confined to its own x sub-band, uniformly divided."""
    total   = sample_total_span()
    ls_list = [sample_cluster_ls(n_clusters, total) for _ in range(n_clusters)]
    budget  = max(total - sum(ls_list), 0.3 * (n_clusters - 1))
    gaps    = expo_gaps(n_clusters - 1, budget)

    # Divide WS into n equal sub-bands, place each cluster's centre in its band
    band_w  = WS / n_clusters
    hw      = band_w * 0.4   # narrow half-width per band
    cxs     = [band_w * (k + 0.5) + random.uniform(-band_w * 0.15, band_w * 0.15)
               for k in range(n_clusters)]
    cxs     = [max(max(ALL_RPOOLS[-1]), min(WS - max(ALL_RPOOLS[-1]), x)) for x in cxs]

    return build_stack(n_clusters, total,
                       cx_fn=lambda k: cxs[k],
                       ls_fn=lambda k: ls_list[k],
                       gap_fn=lambda k: gaps[k],
                       tag_prefix="hs", cfg_id=cfg_id,
                       narrow_hw=hw)


def archetype_top_heavy(cfg_id, n_clusters):
    """C: All clusters in upper half (y > 0), lower half empty."""
    half_span = random.uniform(Y_SPAN_MIN / 2, Y_SPAN_MAX / 2)
    ls_list   = [sample_cluster_ls(n_clusters, half_span) for _ in range(n_clusters)]
    budget    = max(half_span - sum(ls_list), 0.2 * (n_clusters - 1))
    gaps      = expo_gaps(n_clusters - 1, budget)
    cx        = sample_cx()

    elems, start = [], 0
    y = half_span
    for k in range(n_clusters):
        cy  = y - ls_list[k] / 2
        rp  = random.choice(ALL_RPOOLS)
        cp  = random.choice(ALL_CPOOLS)
        n   = random.randint(5, 20)
        c   = make_cluster(cx, cy, n, rp, cp,
                           f"th{k}_{cfg_id}", start_idx=start, ls=ls_list[k])
        elems.extend(c); start += len(c)
        y  -= ls_list[k] + (gaps[k] if k < n_clusters - 1 else 0)
    return elems


def archetype_bottom_heavy(cfg_id, n_clusters):
    """D: All clusters in lower half (y < 0) — mirrors top-heavy."""
    elems = archetype_top_heavy(cfg_id, n_clusters)
    for e in elems:
        e["y"] = round(-e["y"], 5)
    return elems


def archetype_tight_pack(cfg_id, n_clusters):
    """E: Clusters very close — gaps ~ Uniform(0.02*WS, 0.1*Y_SPAN_MAX)."""
    ls_list = [sample_cluster_ls(n_clusters, Y_SPAN_MIN) for _ in range(n_clusters)]
    gaps    = [random.uniform(0.02 * WS, 0.1 * Y_SPAN_MAX)
               for _ in range(n_clusters - 1)]
    total   = sum(ls_list) + sum(gaps)
    cx      = sample_cx()
    return build_stack(n_clusters, total,
                       cx_fn=lambda k: cx,
                       ls_fn=lambda k: ls_list[k],
                       gap_fn=lambda k: gaps[k],
                       tag_prefix="tp", cfg_id=cfg_id)


def archetype_scattered(cfg_id, n_clusters):
    """F: Random (x, y) positions — no vertical structure imposed."""
    total   = sample_total_span()
    min_sep = total / (n_clusters * 2.5)
    cy_list = sorted(random.uniform(-total / 2, total / 2)
                     for _ in range(n_clusters))
    for i in range(1, len(cy_list)):
        if cy_list[i] - cy_list[i-1] < min_sep:
            cy_list[i] = cy_list[i-1] + min_sep

    elems, start = [], 0
    for k, cy in enumerate(cy_list):
        cx  = sample_cx()
        ls  = sample_cluster_ls(n_clusters, total)
        rp  = random.choice(ALL_RPOOLS)
        cp  = random.choice(ALL_CPOOLS)
        n   = random.randint(5, 20)
        c   = make_cluster(cx, cy, n, rp, cp,
                           f"sc{k}_{cfg_id}", start_idx=start, ls=ls)
        elems.extend(c); start += len(c)
    return elems


def archetype_diagonal(cfg_id, n_clusters):
    """G: x drifts linearly from one side to the other as y decreases."""
    total   = sample_total_span()
    ls_list = [sample_cluster_ls(n_clusters, total) for _ in range(n_clusters)]
    budget  = max(total - sum(ls_list), 0.3 * (n_clusters - 1))
    gaps    = expo_gaps(n_clusters - 1, budget)

    x_lo  = random.uniform(0.05 * WS, 0.30 * WS)
    x_hi  = random.uniform(0.70 * WS, 0.95 * WS)
    if random.random() < 0.5:
        x_lo, x_hi = x_hi, x_lo   # random direction
    hw    = WS / (n_clusters * 2.5)

    cxs = [x_lo + (k / max(n_clusters - 1, 1)) * (x_hi - x_lo)
           for k in range(n_clusters)]

    return build_stack(n_clusters, total,
                       cx_fn=lambda k: cxs[k],
                       ls_fn=lambda k: ls_list[k],
                       gap_fn=lambda k: gaps[k],
                       tag_prefix="dg", cfg_id=cfg_id,
                       narrow_hw=hw)


def archetype_two_groups(cfg_id, n_clusters):
    """H: Two tight sub-groups — void ~ Uniform(0.3, 0.7) * Y_SPAN_MAX."""
    n_top     = max(1, n_clusters // 2)
    n_bot     = n_clusters - n_top
    void      = random.uniform(0.3 * Y_SPAN_MAX, 0.7 * Y_SPAN_MAX)
    top_span  = random.uniform(0.1 * Y_SPAN_MAX, 0.3 * Y_SPAN_MAX)
    bot_span  = random.uniform(0.1 * Y_SPAN_MAX, 0.3 * Y_SPAN_MAX)

    def pack_group(n, span, y_top, prefix):
        ls_each = span / max(n, 1)
        tiny_gaps = [random.uniform(0.01, 0.1 * WS) for _ in range(n - 1)]
        y, grp, s = y_top, [], 0
        for k in range(n):
            cx  = sample_cx()
            cy  = y - ls_each / 2
            rp  = random.choice(ALL_RPOOLS)
            cp  = random.choice(ALL_CPOOLS)
            nn  = random.randint(5, 20)
            c   = make_cluster(cx, cy, nn, rp, cp,
                               f"{prefix}{k}_{cfg_id}", start_idx=s, ls=ls_each)
            grp.extend(c); s += len(c)
            y  -= ls_each + (tiny_gaps[k] if k < n - 1 else 0)
        return grp

    y_top = (top_span + void + bot_span) / 2
    return (pack_group(n_top, top_span, y_top, "tg") +
            pack_group(n_bot, bot_span, y_top - top_span - void, "bg"))


def archetype_outlier(cfg_id, n_clusters):
    """I: Main group plus one outlier — outlier gap ~ Uniform(0.4, 0.9)*Y_SPAN_MAX."""
    n_main      = max(1, n_clusters - 1)
    main_span   = random.uniform(0.1 * Y_SPAN_MAX, 0.3 * Y_SPAN_MAX)
    outlier_gap = random.uniform(0.4 * Y_SPAN_MAX, 0.9 * Y_SPAN_MAX)
    outlier_ls  = sample_cluster_ls(1, main_span)
    ls_each     = main_span / max(n_main, 1)

    y, elems, start = main_span / 2, [], 0
    for k in range(n_main):
        cx  = sample_cx()
        cy  = y - ls_each / 2
        rp  = random.choice(ALL_RPOOLS)
        cp  = random.choice(ALL_CPOOLS)
        n   = random.randint(5, 20)
        c   = make_cluster(cx, cy, n, rp, cp,
                           f"om{k}_{cfg_id}", start_idx=start, ls=ls_each)
        elems.extend(c); start += len(c)
        y  -= ls_each + random.uniform(0.05, 0.2 * WS)

    cx_out = sample_cx()
    cy_out = -main_span / 2 - outlier_gap
    rp, cp = random.choice(ALL_RPOOLS), random.choice(ALL_CPOOLS)
    c = make_cluster(cx_out, cy_out, random.randint(4, 15), rp, cp,
                     f"oo_{cfg_id}", start_idx=start, ls=outlier_ls)
    elems.extend(c)
    return elems


def archetype_dense_centre(cfg_id, n_clusters):
    """J: Spacing grows exponentially outward from y=0."""
    base_gap   = random.uniform(0.1 * WS, 0.5 * WS)
    gap_growth = random.uniform(1.5, 3.0)   # each successive gap is larger

    positions, gap = [0.0], base_gap
    for _ in range(n_clusters - 1):
        positions.append(positions[-1] + gap)
        positions.append(positions[0]  - gap)
        gap *= gap_growth
    positions = sorted(set(round(p, 5) for p in positions))[:n_clusters]

    elems, start = [], 0
    for k, cy in enumerate(positions):
        cx  = sample_cx()
        ls  = sample_cluster_ls(n_clusters, Y_SPAN_MAX)
        rp  = random.choice(ALL_RPOOLS)
        cp  = random.choice(ALL_CPOOLS)
        n   = random.randint(5, 20)
        c   = make_cluster(cx, cy, n, rp, cp,
                           f"dc{k}_{cfg_id}", start_idx=start, ls=ls)
        elems.extend(c); start += len(c)
    return elems


# Config builder
def base_config(elements):
    max_r = max(e["r"] for e in elements)

    if ORIENTATION == "vertical":
        # All element centres must be at y < -(r + 0.1) for vertical orientation.
        # Shift the entire stack so the topmost element edge clears y=0 with margin.
        max_y = max(e["y"] for e in elements)
        shift = max_y + max_r + 0.15   # push everything down by this amount
        if shift > 0:
            for e in elements:
                e["y"] = round(e["y"] - shift, 5)

    all_x = [e["x"] for e in elements]
    all_y = [e["y"] for e in elements]

    dom_ymax = 0.0 if ORIENTATION == "vertical" else round(max(all_y) + max_r + 5.0, 3)

    return {
        "alpha_l": 2.0,
        "alpha_t": 0.2,
        "ca": 8.0,
        "gamma": 3.5,
        "dom_xmin": round(min(all_x) - max_r - 2.0, 3),
        "dom_xmax": round(max(all_x) + 150.0, 1),
        "dom_ymin": round(min(all_y) - max_r - 5.0, 3),
        "dom_ymax": dom_ymax,
        "dom_inc": 1.0,
        "num_cp": 40,
        "num_terms": 5,
        "orientation": ORIENTATION,
        "plot_aspect": "",
        "elements": elements
    }


def save_config(name, cfg):
    with open(os.path.join(OUTPUT_DIR, f"{name}.json"), "w") as f:
        json.dump(cfg, f, indent=4)


